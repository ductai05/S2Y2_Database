FROM GIAOVIEN AS GV
WHERE GV.MABM = (SELECT BM.MABM FROM BOMON AS BM, GIAOVIEN AS GV WHERE GV.HOTEN = N'Trần Trà Hương' AND GV.MABM = BM.MABM)

--Q19--
